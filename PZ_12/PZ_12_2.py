# 2. В матрице найти максимальный положительный элемент, кратный 4.

matrix = [
    [3, 8, 1],
    [5, -2, 7],
    [0, 4, 6],
    [9, -1, 2],
    [7, 3, -4]
]

print("\nИсходная матрица:")
list(map(print, matrix))

#Собираем все элементы в плоский список через sum
flat = sum(matrix, [])

#Фильтруем: положительные и кратные 4
filtered = list(filter(lambda x: x > 0 and x % 4 == 0, flat))

#Находим максимум
if filtered:
    max_elem = max(filtered)
    print(f"\nМаксимальный положительный элемент, кратный 4: {max_elem}")
else:
    print("\nТаких элементов нет.")